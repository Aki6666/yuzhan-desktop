/** 从卡片 near 提取配对（双向去重） */
function extractFromNear() {
  const lib = new Map()
  function walk(dir) {
    if (!existsSync(dir)) return
    for (const ent of readdirSync(dir, { withFileTypes: true })) {
      const full = join(dir, ent.name)
      if (ent.isDirectory()) walk(full)
      else if (ent.isFile() && ent.name.endsWith('.json') && ent.name !== 'tags.json' && ent.name !== 'exams.json') {
        try {
          const o = JSON.parse(readFileSync(full, 'utf8'))
          if (o && typeof o.word === 'string') lib.set(o.word, o)
        } catch {
          /* skip */
        }
      }
    }
  }
  walk(IDIOMS_DIR)

  const pairs = new Map()
  const key = (a, b) => (a < b ? `${a}\u0000${b}` : `${b}\u0000${a}`)
  for (const o of lib.values()) {
    for (const n of o.near ?? []) {
      if (!lib.has(n.word)) continue
      const k = key(o.word, n.word)
      if (!pairs.has(k)) pairs.set(k, { a: o.word, b: n.word, diff: n.diff })
    }
  }
  return pairs
}

const result = new Map()
const key = (a, b) => (a < b ? `${a}\u0000${b}` : `${b}\u0000${a}`)
for (const [a, b, diff] of CURATED) result.set(key(a, b), { a, b, diff })
for (const [k, v] of extractFromNear()) if (!result.has(k)) result.set(k, v)

const list = [...result.values()].sort((x, y) => x.a.localeCompare(y.a, 'zh') || x.b.localeCompare(y.b, 'zh'))
const out = { schemaVersion: 1, updatedAt: new Date().toISOString().slice(0, 10), pairs: list }
writeFileSync(OUT, JSON.stringify(out, null, 2) + '\n', 'utf8')
console.log(`pairs.json 生成完成：${list.length} 对（人工精选 ${CURATED.length} + 卡片 near 提取 ${list.length - CURATED.length}）`)
